//
// ───────────────── ⚠️ 本文件是共用层 ⚠️ ─────────────────
// 不得出现任何具体领域的字面量：受托方对每一个行当都是同一批。
// ─────────────────────────────────────────────────────
//
// 【为什么把清单抽成数据，不直接写在 JSX 里】写在 JSX 里的清单没有任何一处能机械核对：
// 漏掉一栏「所在地」、把一条的用途粘成上一条的，页面照常渲染、读起来也完全通顺。
// 而这一页存在的全部意义就是"逐条说清谁拿到了什么、在哪儿"——
// 少一栏就等于那一条没说，判据（terms-processors.test.tsx）按行按栏数。
//
// 【为什么"待确认"是一种取值，不是空字符串】空串会渲染成一个空格子，
// 读的人以为这一栏本来就不需要填。用 { pending } 表示"这里还没定"，
// 页面把它画成醒目的占位，判据也认得出它——**空格子与未定，在页面上必须长得不一样**。

/** 一栏的取值：定了就是那个字；没定就说自己没定，并说清在等谁。 */
export type Cell = string | { readonly pending: string };

export interface Processor {
  /** 受托方名称 */
  readonly name: Cell;
  /** 我们委托它做什么 —— 一句话说清"它拿到什么、拿去干什么" */
  readonly purpose: string;
  /** 所在地（境内 / 境外） */
  readonly location: Cell;
  /** 这一条还要交代的事（默认关闭、要单独同意之类）。没有就不写。 */
  readonly note?: string;
}

export function isPending(cell: Cell): cell is { readonly pending: string } {
  return typeof cell !== 'string';
}

