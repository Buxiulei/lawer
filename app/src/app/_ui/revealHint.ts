/**
 * 低调模式下**两种打码块各自的揭开手势**，以及它们在屏幕上的提示字样。
 *
 * 【为什么必须写字】站内同时存在两套打码，外观都是一层糊：
 *   - 单字段打码 `<Sensitive>`（金额、公司名）：**点一下**显示 3 秒，自动糊回；
 *   - 整块糊层 `[data-veil]`（行动卡、正文、文件名）：**按住 ≥150ms** 才揭开，松手 1.5 秒糊回。
 * 快速点一下糊层是「什么都不发生」——这一下和「页面坏了」在屏幕上长得一模一样。
 * 手势不同却没有任何视觉区分，用户没有办法靠肉眼分辨该点还是该按。
 *
 * 【为什么两处提示的位置不一样】糊层是 `filter: blur()` 打在块自己身上，
 * 而 filter 对整棵子树（含 ::before/::after）一视同仁——**任何贴在糊块上的角标都会跟着糊掉**，
 * 糊掉的角标等于没有。所以：
 *   - `<Sensitive>` 由组件自己渲染，糊只打在内层，角标留在外层是清晰的 → 每块一个角标；
 *   - `[data-veil]` 有 180 余处、且多是服务端组件上的裸属性，角标既进不去也不该进
 *     （180 个角标本身就是一屏噪音）→ 由手势层 DiscreetVeil 出一枚常驻提示，
 *     用过一次（真的按住揭开过）就不再出现。
 *
 * 【字样纪律】这两句会出现在低调模式的屏幕上，必须**不含案情词**（_ui/neutral 的 CASE_WORDS）。
 * 收在这一个文件里是因为同一句要出现在三处（组件角标、手势层提示、开启时的 toast），
 * 分开写就会出现「角标说按住、toast 说点一下」的自相矛盾。
 */

/** 单字段打码（`<Sensitive>`）的手势：点一下，显示 3 秒。 */
export const TAP_HINT = '点一下看清';

/** 整块糊层（`[data-veil]`）的手势：按住不放才揭开。 */
export const HOLD_HINT = '按住看清';

/**
 * 开启低调模式时那一句 toast。
 * **两种手势都要说到**：只说一种，用户会拿这一种去试另一种块，试不动就以为坏了。
 */
export const DISCREET_ON_HINT = `低调模式已开启：糊住的整段${HOLD_HINT}，打码的数字${TAP_HINT}`;
