//
// ───────────────── ⚠️ 本文件是共用层 ⚠️ ─────────────────
// 不得出现任何具体领域的字面量。这里只有一个样式壳，字由调用方给。
// ─────────────────────────────────────────────────────
//
// 【为什么醒目，而不是与正文同色】协议正文里这样的空位有七处，
//「帮助与投诉」页上还有一处服务邮箱。混在正文里的形态是：校对的人一眼扫过去
// 觉得"这句话读得通"，于是它跟着上线——用户读到的是一份在收费与联系方式上
// 写着方括号的合同，而没有任何东西提醒过任何人。
//
// 【为什么不是 danger 色】DESIGN.md 色彩纪律：danger 留给风险与不可逆结论。
// 这里的事实是"还没填"，不是"出事了"。
//
// 【为什么单独一个件，而不是各页各写一段 class】它今天出现在协议页与帮助页两处，
// 将来还会有注册回执。各写一遍的形态是：某天把底色调深一点只改到其中一处，
// 而另一处照常渲染——占位从"一眼看得出"退回"混在正文里"，没有任何东西会报错。
// `data-pending="1"` 是判据抓它的把手（terms-page / help-page 两组各数一次）。

export function Pending({ children }: { children: React.ReactNode }) {
  return (
    <mark
      data-pending="1"
      className="mx-0.5 rounded-[4px] border-l-2 border-amber bg-amber-wash px-1.5 py-0.5 text-[13.5px] font-medium text-amber-ink"
    >
      【{children}】
    </mark>
  );
}
