import { cn } from '@/app/_ui/cn';

/**
 * 品牌小标记：土八鼠头部。
 *
 * **只用头部紧裁，不用全身版**——全身图里「劳动仲裁判决书」「中国劳动法」
 * 两处文字是清晰可读的（c6 档被选中正是因为这两处没糊）。
 * 侧栏这类**应用内持久标记**若用全身版，低调模式糊满整屏正文时，
 * 侧栏却挂着案由文字，**等于替用户公示他在干什么**。头部裁切不含任何文字。
 *
 * **用手绘简化版（`/icon.svg`）而不是原图裁切**，24/28/32px 三档实测比过：
 * 原图裁切在这个尺寸上眼镜糊成一道暗痕、毛发纹理变噪点；
 * 手绘版的眼镜是**干净的黑框白片**，耳朵、牙齿都还在——**小尺寸要的是取舍不是保真**。
 * 顺带两个好处：与 favicon 同一张脸（一个品牌一张脸），且 1KB 而不是 20KB。
 *
 * **绝不在这里引 hero 那张 SVG**：它 778KB / gzip 272KB，而侧栏每页都在——
 * 引它等于每个应用内页面都要拖完整张 hero 才显示一个 24px 的标记。
 * （按 bbox 抽路径做轻量矢量版试过，不成立：vtracer 是层层叠压的色区，
 *   取子集会丢掉眼镜/牙齿/描边，渲染出来是一团色块。字节数看着降了 5.8 倍，像素是废的。）
 *
 * 装饰性用途：alt 留空并 aria-hidden，名字由旁边的文字承担。
 */
export function TubashuMark({ className, size = 24 }: { className?: string; size?: number }) {
  return (
    <img
      src="/icon.svg"
      alt=""
      aria-hidden
      width={size}
      height={size}
      className={cn('shrink-0', className)}
    />
  );
}
