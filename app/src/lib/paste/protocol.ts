// app/src/lib/paste/protocol.ts
// 「回填约定」：让一个调不动工具的客户端，把该进档案的东西写在回复末尾的一个结构块里，
// 用户整段复制粘回网页，服务端解析后逐条确认写入（设计稿 §15 路径 D ②③）。
//
// 【为什么是代码块而不是「请按格式写」】纯文字约定的形态是：模型今天写 JSON、
// 明天写成表格、后天夹在正文里——解析器每次都得猜，而猜错时用户以为记上了，档案里什么都没有。
// 围栏代码块是所有主流聊天客户端都会原样保留的一段（它们连排版都不敢改），
// 复制粘贴过程中最不容易被吃掉的结构。
//
// 【为什么取「最后一个」块】一轮回复里模型可能先示范一个空块、再给真正的那个；
// 也可能把上一轮的块复述一遍。约定「以最后一个为准」在两种情形下都取到本轮的结论，
// 而「取第一个」会把示范块当成结论——它长得完全正常，只是空的。
import type { DomainPack } from '@/lib/domains/registry';

/** 围栏语言标记。解析与生成共用这一个常量，改名只改这里。 */
export const FENCE_TAG = 'tubashu';

/** 结构块里认的五个顶层键。解析、校验、说明书三处共用这一份。 */
export const BLOCK_KEYS = [
  'timeline',
  'actions',
  'claims',
  'deadlines',
  'report_updates',
] as const;

export type BlockKey = (typeof BLOCK_KEYS)[number];

/**
 * 回填约定段的正文。
 *
 * 枚举值现取自案件所属的领域包与时间线词表，**不在这里抄一份**：抄下来的那份会在
 * 某次加种类之后继续对模型说「只能是这几种」，而它写出来的那条在回填时才被拒。
 */
export function buildProtocolSection(input: {
  pack: DomainPack;
  timelineKinds: readonly string[];
}): string {
  const { pack, timelineKinds } = input;
  return [
    PROTOCOL_HEADING,
    '',
    '这类客户端连不了我的档案库，所以**由你把该记的东西写下来，用户复制粘回网页**，由他逐条确认后入库。',
    '规矩只有一条：**你每一次回复的最末尾，都要有一个结构块**（哪怕这一轮没什么可记）。',
    '',
    '```' + FENCE_TAG,
    '{',
    '  "timeline": [{"happened_at": "2026-09-01T10:00:00+08:00", "kind": "公司动作",',
    '                "title": "HR 第一次约谈", "detail": "提出协商解除，未给书面材料"}],',
    '  "actions": [{"what": "把考勤记录导出到个人邮箱", "how": "打开 OA→我的考勤→导出近 12 个月→发到自己邮箱",',
    '               "why": "离职后就打不开 OA 了", "due_at": "2026-09-02T18:00:00+08:00"}],',
    '  "claims": [{"kind": "欠薪", "amount_yuan": 12000, "basis": "用户自述 8 月工资未发"}],',
    '  "deadlines": [{"kind": "举证期限", "anchor_date": "2026-09-01", "days": 10, "note": "通知书上写的"}],',
    '  "report_updates": []',
    '}',
    '```',
    '',
    '**这一轮没有要记的，就原样输出一个空对象 `{}`。** 不要省略这个块，也不要用文字代替它。',
    '',
    '逐项的填法（填不出来的键整个省掉，不要编）：',
    `- \`timeline\`：\`happened_at\` 是事情**发生**的时刻（ISO8601，带时区），不是现在几点；\`kind\` 只能是 ${timelineKinds.join(' / ')}；\`title\` 一句话说清发生了什么。`,
    '- `actions`：四样齐了才算一张卡——`what` / `how`（具体到照着做）/ `why`（一句）/ `due_at`（ISO8601 时刻，「今天下班前」要换算成具体时刻）。',
    `- \`claims\`：\`kind\` 只能是 ${pack.calculatorKinds.join(' / ')}；\`amount_yuan\` 单位是**元**（我这边换算成分）。**算得出来的项不要自己填金额**，填 0、把依据写进 \`basis\` 就行——金额由服务端的算钱器出，你心算的数会被拒收。`,
    `- \`deadlines\`：\`kind\` 只能是 ${pack.deadlineKinds.join(' / ')}；\`anchor_date\` 是起算那一天（YYYY-MM-DD）；到期日**由服务端按规则推算**，不要自己算；只有天数由办案机构在通知书上指定的那类才填 \`days\`，照通知书上写的填。`,
    '- `report_updates`：本站的个案报告还没上线，这一项先给空数组。',
    '',
    '**块外的正文会被丢弃**：解释、寒暄、免责声明写在块外面没关系，但**不要把要记的内容只写在块外**——',
    '那些字进不了档案，而用户会以为记上了。反过来也不要把整段回复塞进块里，块里只放结构化的那几条。',
    '',
    '**每开一个新对话，用户都要把这段开场白重贴一次**：这类客户端记不住上一轮，',
    '你手上的事实卡就是他贴给你的这一份，不要假设自己还记得别的。',
  ].join('\n');
}

/** 回填约定段的小标题。判据按它认段。 */
export const PROTOCOL_HEADING = '## 回填约定（每次回复末尾都要有）';
