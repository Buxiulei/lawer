// app/src/lib/company/normalize.ts
// company_key 的**唯一产地**。档案是跨案共享的平台资产，company_key 同时是缓存键与计费键；
// 键算错的后果是双向的：算宽了两家不同的公司共用一份档案（用户付了 A 家的钱、拿到 B 家的判例，
// 而且档案本身看起来完全正常），算窄了同一家公司被反复建档反复收费。
//
// 【为什么必须只有一个入口】教训「修入口不修五处」：归一化规则一旦散落在多处，
// 补规则的人只会改自己手边那一处，另外几处继续按旧规则算——而两处算出不同的键时，
// 系统不报错，只是缓存不命中、或者命中了错的那份，表现为「报价时判为已有存档、
// 建档时又新建一条」这种一半便宜一半全价的账。本文件是唯一写点，
// 由 __tests__/normalize.test.ts 的两条结构守卫点名（新文件里出现自造归一化即红）。
//
// ── ⚠️ 合并裁决（2026-08-31，ws/dossier-pipeline × ws/dossier-billing）⚠️ ──
// 两支各自写过一版归一化，规则强度不同，合并时**按误差方向取保守的那一版**：
//   · 归一化过度 ⇒ 两家**不同**主体撞同一个 company_key ⇒ 用户付了 A 的钱拿到 B 的档案，
//     全程没有任何一处会报错。这是静默且不可事后发现的方向。
//   · 归一化不足 ⇒ 同一家公司的两种写法各建一档 ⇒ 多付一次全价、我们多采一次。
//     这个方向亏钱、可退、可事后合并，且用户看得见（页面会显示「本公司暂无存档」）。
// 故**去掉**了采集管线那版里的两条规则，理由写在下面各自的位置：
//   ① 繁简对照小表（廣→广 一类）：需要一份可核对的对照数据才做，凑几个常用字的表看起来做了而已；
//   ② `有限责任公司 ≡ 有限公司`：工商登记的是**全称精确串**，这两个名字可以是两家不同主体。
// 保留的是计费侧那版的 NFKC 保守归一 + **采集管线那版的命名空间前缀**（见 companyKey）。
// 要放宽（补回繁简/后缀等价）时，请连同一份可核对的对照数据与「误合并」的回滚手段一起做，
// 别只加函数——补规则等于把一批既有的 company_key 变成另一个值，存量档案会当场全部落空。
//
// 【范围声明，别当通用工具用】这里做的是**中国大陆企业名的最小归一**，不是通用文本清洗。
// **可靠的键是统一社会信用代码**：填了 uscc 就完全绕开名称归一化这摊事。

/**
 * 公司名归一化：只做 Unicode 兼容分解合成（NFKC）+ 去全部空白 + 大小写归一。
 *
 * NFKC 一步覆盖了「全半角」那条：全角括号 `（）`、全角字母数字、全角逗号句号
 * 都会被折成半角形式，故不需要再手写一张标点对照表（手写的那张一定会漏字符）。
 * 去空白覆盖「北京 甲 科技」这类粘贴带进来的空格、全角空格与不间断空格。
 *
 * 刻意**不做**的五件事（前三条见文件头的合并裁决）：
 *  1. 不做繁简合并；
 *  2. 不做 `有限责任公司 → 有限公司` 一类的后缀等价；
 *  3. **不删「有限公司」等组织形式后缀**——删了之后「某某有限公司」与「某某股份有限公司」
 *     会合并，那是两个不同的法律主体；
 *  4. **不删括号里的地名**。「某某咨询（北京）有限公司」与同名的（上海）公司是两家公司，
 *     括号内容是区分它们的唯一线索，NFKC 只把全角括号折成半角；
 *  5. 不做同音/近似合并，不截断长度。
 */
export function normalizeCompanyName(name: string): string {
  return name.normalize('NFKC').replace(/\s+/gu, '').toLowerCase();
}

/**
 * 档案主键：**统一社会信用代码优先，缺了才退回归一化名称**。
 *
 * 为什么带 `uscc:` / `name:` 前缀：两个命名空间不能撞。一个 18 位的 uscc 与一个恰好
 * 由数字组成的名称在裸串下可能相等，前缀让「按代码认」与「按名字认」在库里永远分得开，
 * 也让人一眼看得出这条档案的身份是硬的（有代码）还是软的（只有名字）。
 * uscc 是登记机关发的唯一标识，不受名称写法与更名影响：填了它，更名不换档。
 *
 * 空名 + 空代码直接抛错，不返回一个空键：一个空 company_key 会被 UNIQUE 约束
 * 变成「全站共用一份档案」，所有这类请求互相看到对方的数据——那是最糟的静默错误。
 */
export function companyKey(input: { uscc?: string | null; name?: string | null }): string {
  const uscc = (input.uscc ?? '').normalize('NFKC').replace(/\s+/gu, '').toUpperCase();
  if (uscc) return `uscc:${uscc}`;
  const name = normalizeCompanyName(input.name ?? '');
  if (!name) {
    throw new Error(
      'company_key 算不出来：公司名为空——归一化（去空白、全角折半角）之后没剩下任何字符，' +
        '统一社会信用代码也是空的。档案按 company_key 唯一，空键会让所有这类请求' +
        '共用同一条档案、互相看到对方的数据；' +
        '请至少提供公司全名（工商登记的公司全称），或直接填统一社会信用代码后重试。',
    );
  }
  return `name:${name}`;
}
