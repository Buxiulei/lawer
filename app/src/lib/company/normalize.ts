// app/src/lib/company/normalize.ts
// company_key 的**唯一生成入口**。别在别处再写第二个归一化——company_key 是
// company_dossiers 的 UNIQUE 列，它同时是缓存键与计费键：两处算法分叉，
// 就会出现「报价时判为已有存档、建档时又新建一条」这种一半便宜一半全价的账。
//
// ── ⚠️ 归一化只做**可逐字验证**的那几步，故意做得保守 ──
// 设计稿原话是「去括号全半角、去『有限公司』后缀差异、繁简归一」。后两条本文件**没有实现**，
// 这是有意的，理由是误差方向：
//   · 归一化过度 ⇒ 两家**不同**主体撞同一个 company_key ⇒ 用户付了 A 公司的钱、
//     拿到 B 公司的档案，而且档案本身看起来完全正常，没有任何一处会报错。
//   · 归一化不足 ⇒ 同一家公司的两种写法各建一档 ⇒ 用户多付一次全价、我们多采一次。
//     这个方向亏钱、可退、可事后合并，且用户看得见（页面会显示「本公司暂无存档」）。
// 「甲科技有限公司」与「甲科技有限责任公司」在工商登记上可以是两家不同主体；
// 「繁简归一」需要一张真的繁简对照表，凑几个常用字的假表比不做更危险——它看起来做了。
// **可靠的键是统一社会信用代码**：填了 uscc 就完全绕开名称归一化这摊事。
// 需要补齐后两条时，请连同一份可核对的对照数据与「误合并」的回滚手段一起做，别只加函数。

/**
 * 公司名归一化：只做 Unicode 兼容分解合成（NFKC）+ 去全部空白 + 大小写归一。
 *
 * NFKC 一步覆盖了「全半角」那条：全角括号 `（）`、全角字母数字、全角逗号句号
 * 都会被折成半角形式，故不需要再手写一张标点对照表（手写的那张一定会漏字符）。
 * 去空白覆盖「北京 甲 科技」这类粘贴带进来的空格与不间断空格。
 */
export function normalizeCompanyName(name: string): string {
  return name.normalize('NFKC').replace(/\s+/gu, '').toLowerCase();
}

/**
 * 生成 company_key：有统一社会信用代码就用它（大写去空白），否则用归一化后的公司名。
 * uscc 优先是因为它是**登记机关发的唯一标识**，不受名称写法与更名影响。
 * @throws 名称归一化后为空（只填了空白/纯符号）时抛——空 key 会把所有这类请求撞进同一条档案。
 */
export function companyKeyOf(input: { name: string; uscc?: string | null }): string {
  const uscc = (input.uscc ?? '').normalize('NFKC').replace(/\s+/gu, '').toUpperCase();
  if (uscc) return uscc;
  const key = normalizeCompanyName(input.name);
  if (!key) {
    throw new Error(
      '公司名为空：归一化（去空白、全角折半角）之后没剩下任何字符。' +
        '公司名是档案的唯一键，空名会让所有这类请求共用同一条档案、互相看到对方的数据。' +
        '请填写工商登记的公司全称，或直接填统一社会信用代码。',
    );
  }
  return key;
}
