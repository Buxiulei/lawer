// app/src/lib/company/normalize.ts
// company_key 的**唯一产地**。档案是跨案共享的平台资产，缓存命中与否全看这把键；
// 键算错的后果是双向的：算宽了两家不同的公司共用一份档案（把别人的判例摆给用户看），
// 算窄了同一家公司被反复建档反复收费。
//
// 【为什么必须只有一个入口】教训「修入口不修五处」：归一化规则一旦散落在多处，
// 补规则的人只会改自己手边那一处，另外几处继续按旧规则算——而两处算出不同的键时，
// 系统不报错，只是缓存不命中、或者命中了错的那份。本文件是唯一写点，
// 由 __tests__/normalize.test.ts 的结构守卫点名（新文件里出现自造归一化即红）。
//
// 【范围声明，别当通用工具用】这里做的是**中国大陆企业名的最小归一**，不是通用文本清洗：
// 全半角、空白、繁简（一张针对企业名用字的小表，不是通用繁简转换器）、
// 以及一条明确的后缀等价（有限责任公司 ≡ 有限公司）。
// 刻意**不做**的事都在下面各自写了理由——它们不是没来得及做，是不该做。

/** 全角 ASCII（！～）→ 半角。企业名里的（）／，与英文数字都会被这一步拉齐。 */
function toHalfWidth(s: string): string {
  return s
    .replace(/[！-～]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0xfee0))
    .replace(/　/g, ' '); // 全角空格没落在上面那段区间里，单独处理
}

/**
 * 企业名常见繁体字 → 简体。
 *
 * 【为什么是一张小表而不是通用转换】通用繁简转换要处理一简对多繁（「發/髮」→「发」）
 * 这类歧义，做错了会把两家不同的公司合并成一家。企业名的用字集很窄，
 * 逐字核过的小表在这个场景里比一个「大致正确」的通用转换器更安全，
 * 而它的失效方式也是安全的：表里没有的字原样保留 ⇒ 至多不命中缓存，绝不错误合并。
 * 需要扩表时逐字加，并在 normalize.test.ts 里补一条用例。
 */
const TRAD_TO_SIMP: Record<string, string> = {
  責: '责', 務: '务', 業: '业', 產: '产', 資: '资', 際: '际', 國: '国',
  區: '区', 開: '开', 發: '发', 貿: '贸', 電: '电', 網: '网', 訊: '讯',
  諮: '咨', 詢: '询', 銷: '销', 營: '营', 團: '团', 華: '华', 東: '东',
  廣: '广', 陝: '陕', 遼: '辽', 寧: '宁', 濟: '济', 澤: '泽', 興: '兴',
  龍: '龙', 鳳: '凤', 豐: '丰', 億: '亿', 萬: '万', 順: '顺', 誠: '诚',
  遠: '远', 財: '财', 經: '经', 銀: '银', 險: '险', 醫: '医', 藥: '药',
  機: '机', 車: '车', 輪: '轮', 鋼: '钢', 鐵: '铁', 環: '环', 節: '节',
  運: '运', 輸: '输', 廠: '厂', 場: '场', 樓: '楼', 設: '设', 計: '计',
  診: '诊', 監: '监', 護: '护', 標: '标', 準: '准', 據: '据', 檢: '检',
  測: '测', 驗: '验', 應: '应', 對: '对', 專: '专', 種: '种', 農: '农',
  漁: '渔', 礦: '矿', 傳: '传', 諾: '诺', 達: '达', 創: '创', 聯: '联',
};

function toSimplified(s: string): string {
  return [...s].map((ch) => TRAD_TO_SIMP[ch] ?? ch).join('');
}

/**
 * 企业名归一化。**只做等价变换，不做信息删除。**
 *
 * 刻意不做的四件事：
 *  1. **不删「有限公司」后缀**。删了之后「某某有限公司」与「某某股份有限公司」会合并——
 *     那是两个不同的法律主体。只把 `有限责任公司` 归到 `有限公司`（这两个确实是同一种组织形式
 *     的两种写法），`股份有限公司` 原样保留。
 *  2. **不删括号里的地名**。「宜信普惠信息咨询（北京）有限公司」与同名的（上海）公司
 *     是两家公司，括号内容是区分它们的唯一线索，只把全角括号拉成半角。
 *  3. **不做同音/近似合并**。「宜信」与「易信」长得像不是合并的理由。
 *  4. **不截断长度**。
 */
export function normalizeCompanyName(name: string): string {
  const s = toSimplified(toHalfWidth(name))
    .replace(/\s+/g, '') // 企业名内部的空白一律无意义（录入换行/多空格），全去掉
    .toLowerCase()
    .replace(/有限责任公司/g, '有限公司');
  return s;
}

/**
 * 档案主键：**统一社会信用代码优先，缺了才退回归一化名称**。
 *
 * 为什么带 `uscc:` / `name:` 前缀：两个命名空间不能撞。一个 18 位的 uscc 与一个恰好
 * 由数字组成的名称在裸串下可能相等，前缀让「按代码认」与「按名字认」在库里永远分得开，
 * 也让人一眼看得出这条档案的身份是硬的（有代码）还是软的（只有名字）。
 *
 * 空名 + 空代码直接抛错，不返回一个空键：一个空 company_key 会被 UNIQUE 约束
 * 变成「全站共用一份档案」，那是最糟的静默错误。
 */
export function companyKey(input: { uscc?: string | null; name?: string | null }): string {
  const uscc = (input.uscc ?? '').trim().toUpperCase();
  if (uscc) return `uscc:${uscc}`;
  const name = normalizeCompanyName(input.name ?? '');
  if (!name) {
    throw new Error(
      'company_key 算不出来：统一社会信用代码与公司名都是空的。' +
        '档案按 company_key 唯一，空键会让所有公司共用同一份档案；' +
        '请至少提供公司全名（或统一社会信用代码）后重试。',
    );
  }
  return `name:${name}`;
}
