/**
 * 首诊「合同签订次数」那一格的自述里，哪些答案的意思是**一份书面合同都没有**。
 *（要件卡 `双倍工资-2` 的 slotChecks 用它；机制见 lib/cases/elements.ts 的 SlotValueCheck。）
 *
 * 这一格是自由文本（intakeSchema 里 kind='text'，「用户自述原样记录」），所以什么都可能填：
 * 「没签」「一份都没有」「0」「2 次」「续签过一次」「不记得了」「签了无固定期限」。
 *
 * 【认不准时一律判"不算"】两个方向的错代价不对等：把"签过两次"误认成"没签"，
 * 二倍工资那一项会显示「成立·待证」，用户据此去主张一笔提不了的钱；反过来判成「缺失」，
 * 只是让他多回答一句"你到底签没签"。所以只有明确说了没有的答案才算数，
 * 「不记得」「待确认」这类一律不算（回「缺失」，出路见那张卡的 typicalEvidence）。
 *
 * 【第二次复审 2026-09-10 点名的那一类错法】此前最后一步是"剩下的看有没有否定词 /[没未无]/"，
 * 于是「无固定期限」「未续签」「签过，后来没续签」「签了但没盖章」——**全是签过**的说法——
 * 都被判成"没签"。北京老员工最常见的那个答案（「签了无固定期限合同」）正落在里面。
 * 现在的次序是：先认"签过"的形态（续签、合同期限的说法、肯定式的"签了/签过"），
 * 再要求否定词**紧挨着**「签 / 订 / 合同」才算数。
 */
function noWrittenContract(raw: string): boolean {
  const s = raw.replace(/\s+/g, '');
  if (s === '') return false;
  // ①「一次都没签」「一份也没有」「一份没有」——这一类自己带着"一次/一份"，要先认，
  //   否则会被③按"报出了次数"判成签过。
  if (/[一1１][次份回][都也]?[没未]/.test(s)) return true;
  // ②「0」「0 次」「零份」——整格就是一个零。
  if (/^[0０零]+[次份回]?$/.test(s)) return true;
  // ③ 报出了次数 ⇒ 签过（「2 次」「两份」「续签过一次」）
  if (/[1-9１-９一二两三四五六七八九十][次份回]/.test(s)) return false;
  // ④「续」字出现即签过：续签 / 未续签 / 没续签 / 后来没续——能"续"的前提是先签过一份。
  if (/续/.test(s)) return false;
  // ⑤「无固定期限」「固定期限」说的是**合同期限**，不是"没有合同"。
  //   这是本行当最常见的那个答案，也是上一版最贵的那处误判。
  if (/期限/.test(s)) return false;
  // ⑥ 肯定式的"签了 / 签过 / 已签"⇒ 签过。**否定式要先排掉**（「没签过」「没有签过」里
  //   也含"签过"两个字），所以第二个正则是它的例外。
  if (/[签订][了过完的]|已[签订]/.test(s) && !/[没未不][有]?[签订][了过完的]/.test(s)) return false;
  // ⑦ 到这里才轮到否定词，而且**必须紧挨着**「签 / 订 / 合同」：
  //   「没盖章」「没给我」说的都是别的事，它们不代表一份合同都没有。
  if (/[没未无别][有]?[签订]/.test(s)) return true;
  if (/[没未无][有]?(书面)?合同/.test(s)) return true;
  // ⑧ 整格就是一个光杆否定（「无」「没有」「从来没有」）。
  if (/^(从来|从没|一直|压根|根本|至今)?[没未无][有]?$/.test(s)) return true;
  // ⑨ 剩下的一律认不准 ⇒ 不算（「不记得」「HR 说回头补」「待确认」）。
  return false;
}

