// app/src/lib/knowledge/precedent-line.ts
// 一条「解释存疑」项下面那行「过往相似案例」的**唯一**措辞。
//
// 【为什么它是一个独立模块，而不是各处各写一句】这一行同时出现在两个出口：
// 每轮都在的事实卡（lib/agent/case-facts.ts）与存下来的个案报告（lib/cases/report.ts）。
// 各写一份的形态是——两处的空臂说法不一样（一处写"库里暂无"、另一处干脆省掉这一行），
// 于是"查过没找到"与"没人查过"在其中一个出口上又变回同形，而两份文本各自读起来都正常。
// 判据也只能各钉一份，改其中一处不会红。
//
// 【为什么住在 lib/knowledge 而不是 lib/agent】lib/agent/case-facts.ts 已经从
// lib/cases/report.ts 取 basicsMissing；把这一行留在 case-facts 里再让 report 反向引用，
// 就成了 cases ↔ agent 的循环依赖。这一行要的只是"按 id 取卡名"，那是 knowledge 的事。
import { titleOf } from './index';

/**
 * 一条存疑项下面那行「过往相似案例」。**没有案例时照样出这一行**。
 *
 * 【为什么空的时候不能省掉这一行】主理人 2026-09-07 裁决：解释存疑时应先找过往相似判例。
 * 省掉的形态是——模型读到一条光秃秃的"现行法律解释存疑"，既不知道库里有没有判过的，
 * 也没有任何东西告诉它"库里确实没有"；于是它要么跳过这一步，要么**顺手编一个案例填上**，
 * 而编出来的案例读起来最像尽责。写出"库里暂无"，才把"查过没找到"与"没人查过"分开。
 *
 * 【为什么每条案例后面都跟着"个案不是规则"】这一节存在的全部理由是"这几件事没有定论"。
 * 只把案例摆出来的形态是：模型拿一个个案的判法当成定论答给用户——它引了官方来源、
 * 摆了真实数字，看起来比"存疑"那句话可信得多，而它恰好推翻了这一节要立的东西。
 *
 * 【空臂那句话为什么写这么长】判据按**整句**数它出现了几次（应等于没挂卡的条目数）。
 * 只数"库里暂无官方相似案例"这半句的形态是：领域包的纪律句里本来就写着这半句，
 * 于是那条断言在一条空臂都没渲染出来的时候照样绿——它数到的是纪律句自己。
 */
export const NO_PRECEDENT_LINE =
  '过往相似案例：库里暂无官方相似案例（缺口已登记）。不许拿转载站、公众号或印象补一个上去。';

export function precedentLine(ids: readonly string[]): string {
  if (!ids.length) return NO_PRECEDENT_LINE;
  const titles = ids.map((id) => `《${titleOf(id) ?? id}》`).join('；');
  return `过往相似案例（先检索再引用，每个都要说明谁发布的、实际怎么判的）：${titles}。` +
    '**个案不是规则**：只能证明"这一个案子是这么判的"，不能拿去套本案，也不能当成这一条已有定论。';
}
