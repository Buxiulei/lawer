// app/src/lib/billing/in-flight.ts
// 「同一个人同时只答一轮」的在飞占位。
//
// 【为什么余额闸自己不够】闸读的是 gongdao.balance，而这一轮花了多少要等答完才结算。
// 于是余额 1 的人同时点两下（手机上双击发送、两个标签页各问一句），两个请求读到的
// 都是 1，两轮都放行、两轮都跑完——「最多欠一轮」当场变成欠两轮，账上多出一笔消耗，
// 而两边屏幕上各自都在好好答题，看不出任何异样。闸是逐轮判的，欠账却是并发发生的。
//
// 【为什么是进程内的一格，不是数据库里的一行】生产是裸 systemd 单进程（deploy/），
// 同一个人的两个请求必然落在同一个进程里，这个 Set 就是全部事实。多进程/多机那天
// 换成一张 holds 表的一行（user_id 唯一键 + 取得时刻 + 过期回收）即可：判据不变、
// 调用点不变，要改的只有这个文件。
// 进程重启 = 全部释放，这正是对的：那一刻在飞的那些轮本来也随进程一起没了。
//
// 【释放是调用方的 finally 的事】占位不设超时自动回收：一个不会释放的占位等于把这个人
// 永久锁在门外，而超时回收会在「模型想了四分钟」这种正常情形上放第二轮进来（正是本文件
// 要拦的那件事）。所以取位的人必须在 finally 里释放——异常、断线、走人，都走那一条路。

/** 此刻正有一轮在跑的用户。单进程假设见文件头。 */
const inFlight = new Set<number>();

/** 这个人此刻有没有一轮还在跑。闸（canStartTurn）拿它判 IN_FLIGHT。 */
export function isTurnInFlight(userId: number): boolean {
  return inFlight.has(userId);
}

/**
 * 占住这个人的那一格，返回释放函数（**调用方必须在 finally 里叫它**）。
 *
 * 调用前应当已经过闸（canStartTurn）：这里只负责占位，不重判。
 * 判与占之间不许有 await——中间让出一次事件循环，另一个请求就会在同一个「没人占位」
 * 的快照上过闸，本文件就白写了。路由里两句紧挨着，并发判据钉的就是这件事。
 *
 * 释放函数幂等，且只释放**自己那一次**占位：叫过一次之后再叫是空操作，
 * 不会把后来那一轮刚占上的格子顺手删掉。
 */
export function beginTurn(userId: number): () => void {
  inFlight.add(userId);
  let released = false;
  return () => {
    if (released) return;
    released = true;
    inFlight.delete(userId);
  };
}

/**
 * 撞上在飞时对外说的那句话，自述三段式：**怎么了 / 为什么 / 怎么办**。
 * 与判定同处一处（同 gongdaoExhaustedMessage 的理由）：在路由里就地拼一句，
 * 下一处需要拦的地方会照抄那一份。
 */
export function turnInFlightMessage(): string {
  return (
    '上一轮还在答，等它结束。' +
    '同一个账号一次只答一轮——一轮的花费要等答完才结算，' +
    '两轮同时开就会各自按「还没扣钱」的余额放行，最后一起扣。' +
    '等上面那一轮答完（或者点停止）再问这一句。'
  );
}
