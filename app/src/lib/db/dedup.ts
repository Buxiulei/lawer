// app/src/lib/db/dedup.ts
// 写入去重用的标题规范化键：去掉空白与标点后逐字比较。
//
// 【为什么规范化而不是直接等值比】重试重放时模型往往一字不差，但也会把
// 「调岗通知」写成「调岗通知。」、多敲一个空格、或把全角括号换半角——那是同一件事的
// 两种写法，不该在档案里落成两条（生产 case2 实测：同一次调岗写成两条时间线、
// 三张行动卡各写两遍）。去空白与标点后，这些差异塌缩成同一个键。
//
// MCP、REST、站内 agent 三条写路径共用这一个函数：各写一份判等逻辑，某天必然漂移，
// 于是同一件事在一条路径上被拦、在另一条上又漏进去。

/**
 * 去掉所有空白与标点（\p{P} 覆盖中英文标点与全/半角括号），返回用于去重比较的键。
 * 不折叠大小写、不动符号（＋、￥ 之类）——那些不是「标点」，塌缩它们会把不同的数值写法误判成同一条。
 */
export function dedupTitleKey(title: string): string {
  return title.replace(/[\s\p{P}]/gu, '');
}
