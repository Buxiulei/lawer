// app/src/lib/complaints-policy.ts
// 投诉 / 举报 / 个人信息权利请求这条入口的**对外口径**：三种类型、两个时限、两道长度闸。
//
// ───────────────── ⚠️ 本文件是共用层 ⚠️ ─────────────────
// 不得出现任何具体领域的字面量：这条入口对每一个行当都是同一条。
// ─────────────────────────────────────────────────────
//
// 【为什么与 lib/complaints.ts 分成两个文件】那一份要查库、要加解密，
// 引它就把 better-sqlite3 与 node:crypto 拖进来；而这几个常量**表单要用**——
// 表单是客户端件。合在一份的形态是：客户端组件 import 一个数字，
// 顺带把数据库驱动打进浏览器包（同 lib/ai-label 与 lib/ai-label-case 的分法）。
//
// 【为什么时限要收成常量】它出现在三处：协议第十二条、「设置 → 帮助与投诉」页、
// 提交后的受理回执。三处各写一遍的形态是——改一次口径只改到其中两处，
// 而另一处照常渲染、读起来完全像一句承诺，只是它承诺的是另一个数。
// 《生成式人工智能服务管理暂行办法》第十五条要的正是「公布处理流程和反馈时限」：
// 公布了两个互相打架的时限，比没公布更糟。

/** 受理确认的时限（工作日）。协议第十二条第 1 款逐字承诺的那个数。 */
export const COMPLAINT_ACK_WORKDAYS = 3;
/** 答复处理结果 / 个人信息权利请求办结的时限（工作日）。 */
export const COMPLAINT_REPLY_WORKDAYS = 15;

/**
 * 三类请求。**分开而不是合成一个「反馈」**：它们后面接的处理流程不一样——
 * 举报要按《生成式人工智能服务管理暂行办法》第十四条判违法内容并可能上报主管部门，
 * 个人信息权利请求要在 15 个工作日内办结并对拒绝说明理由，而投诉是产品问题。
 * 合成一类的形态是：一条「请把我的信息删掉」躺在产品反馈堆里，谁也没意识到它有法定期限。
 */
export const COMPLAINT_KINDS = ['投诉', '举报', '个人信息权利请求'] as const;
export type ComplaintKind = (typeof COMPLAINT_KINDS)[number];

/** 每一类在表单上的一句话说明：选错类型的代价是它排进另一条流程，用户看不出来。 */
export const COMPLAINT_KIND_HINTS: Readonly<Record<ComplaintKind, string>> = {
  投诉: '服务本身出了问题：算错、答非所问、扣费不对、页面用不了。',
  举报: '本服务生成的内容违法或侵害了谁的权益。任何人都可以举报，不限于本人的档案。',
  个人信息权利请求: '查阅、复制、更正、删除你的个人信息，撤回同意，导出整案副本，注销账号。',
};

/** 描述的长度闸。下限挡的是空提交，上限挡的是把整个案卷粘进来。 */
export const COMPLAINT_BODY_MIN = 5;
export const COMPLAINT_BODY_MAX = 4000;
/** 联系方式：手机号、邮箱或任何对方留得下的写法，只挡空与超长。 */
export const COMPLAINT_CONTACT_MAX = 200;
