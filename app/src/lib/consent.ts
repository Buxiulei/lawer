// 同意的**唯一词表与文案源**：有哪几类同意、每类的版本、以及各处要念给用户听的那几句话。
//
// 【为什么是一个不引 db 的纯常量文件】登录页、实名卡、设置页都是**客户端组件**，
// 它们要显示这些话。若把这些常量放在 lib/db/consents.ts 里，浏览器包会连带把
// better-sqlite3 拖进去（同 lib/auth/guard.ts 抬头那条理由）。所以分两层：
// 话在这里，落库在 lib/db/consents.ts。
//
// 【为什么 kind 要收成一份】同一类同意有四个读写方（注册页、实名页、站内对话、设置页）。
// 各处手写字符串的形态是：某处写成 'realname-adopt'、另一处写 'realname_adopt'，
// 于是「已经同意过」在一个页面上成立、在另一个页面上不成立，而两边都不报错。
//
// ───────────────── ⚠️ 本文件是共用层 ⚠️ ─────────────────
// 不得出现任何具体领域的字面量（领域名、词表、口径措辞）。这里的每一句话都要在
// 两个领域里同样成立——同意与个人信息是账号层面的事，不是某个行当的事。
// ─────────────────────────────────────────────────────
//
// 依据：docs/legal/用户服务协议-草案.md（v0.2）附一「产品同步清单」#1–#6 与对应条款。

