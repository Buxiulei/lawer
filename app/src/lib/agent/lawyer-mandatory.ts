// app/src/lib/agent/lawyer-mandatory.ts
// 「法律上只能由执业律师做的那几件事」在 system prompt 里的那一段。
//
// 【这是共用层唯一允许把用户指向律师的地方】主理人 2026-09-07 裁决：能我们的智能体
// 完成的都我们来做，实在绕不过去、必须要律师签字背书的才建议去找律师，不向用户推卸责任。
// 落到代码上就是：**清单在领域包里（DomainPack.lawyerMandatory），话在这里，别处不许说**——
// 产品面与 charter 里出现「律师」只有三个合法位置（否定式免责 / 本段渲染 / 法条原文），
// 由 app/__tests__/lawyer-referral-guard.test.ts 按文件扫。
//
// 【为什么禁令必须配一份闭合清单，而不是只写一句"不许劝找律师"】只禁不给出路的规范，
// 最省力的满足方式是**含糊**——把"这个得找律师"改写成"这类问题通常需要专业支持"，
// 判据不响、用户照样被支了出去。给出清单之后，模型每一次提到律师都要落到某一条上，
// 落不上的就只剩一条路：自己把活干完。
//
// 【为什么它每轮都在，而不是命中才给】它防的是**模型的默认行为**（收尾时顺手加一句
// "建议咨询专业律师"），不是某一种输入。只在用户问到时才注入的形态是：用户没问、
// 模型自己收了这么一句尾，而那一轮回复读起来完全正常，没有一处会报错。

import type { DomainPack } from '@/lib/domains/registry';

/** 这一段的抬头。判据按它认段，改字要连判据一起改。 */
export const LAWYER_MANDATORY_HEADING = '## 只有这几件事法律上必须由执业律师做（本段之外不许把用户支出去）';

/**
 * 渲染那一段。条目逐条来自领域包，**共用层一条都不写死**：写死的形态是，
 * 第二个领域的用户读到的是上一个行当的清单，而这一轮回复照常生成、没有一处会报错。
 */
export function renderLawyerMandatory(pack: DomainPack): string {
  return [
    LAWYER_MANDATORY_HEADING,
    '',
    ...pack.lawyerMandatory.map((item) => `- **${item.label}**：${item.why}（依据：${item.basis}）`),
    '',
    '这份清单是**闭合的**，本轮纪律：',
    '1. **清单以外的每一件事，都由你做完**——查依据、算金额、起草文书、列证据目录、排期限、',
    '   预演流程、写可照读的原句。做不动的那一步就说清卡在哪、需要用户提供什么，',
    '   **不许把它交回给用户去"找人问"**。',
    '2. 清单以内的事项：说明「这一项法律上必须由执业律师做」+ 为什么 + 依据的条号，',
    '   并**同时交代我们已经替他做完的那一半**（材料、算式、时间线、可直接交出去的文件）。',
    '   只说边界不给下一步，就是把人推回没人管的地方。',
    '3. **禁止用「建议咨询律师」「这个还是得找律师」「请专业人士复核一下」这类话收尾**，',
    '   也禁止把它们改写成「这类问题通常需要专业支持」这种含糊说法——含糊的版本更难被发现，',
    '   而用户读到的是同一句：这里帮不了你。',
    ...lawyerReviewTiebreak(pack),
  ].join('\n');
}

/**
 * 第 4 条：本领域若另有一节「待律师书面确认」（DomainPack.lawyerReview），**它与本段谁管谁**。
 *
 * 【为什么必须在同一段里写死先后】那一节每轮随案件事实卡渲染，逐条写着"待律师书面确认"；
 * 本段第 1 条又写着"清单以外的每一件事都由你做完"、第 3 条写着"不许用建议咨询律师收尾"。
 * 两条指令在同一份 system prompt 里对着同一个问题（"我们机构算不算强制报告主体"）
 * 给出相反的动作，而**两种做法都不会报错**：按本段办就给出是/否结论（正是那一节要禁的），
 * 按那一节办就把人指向了律师（正是本段要禁的）。谁优先不写下来，等于交给模型当场掷骰子。
 *
 * 【裁法】那一节限制的是**结论**，本段限制的是**动作**——所以两者不冲突，
 * 只是需要说出来：待确认项照第 1 条把能做的做完（争议、依据、要确认的是哪一句），
 * 只是不下"是/否"的结论；说"这一句要有书面签字"不算把人支出去，
 * 而"这个你去问律师吧"仍然违反第 1 条。
 *
 * 【为什么按 pack 有没有这一节来出这一条，而不是共用层写死】没有这一节的领域读到
 * "本领域另有一节……"是指着一个不存在的东西说话，而它读起来完全通顺——
 * 模型只会照着编一个出来。
 */
function lawyerReviewTiebreak(pack: DomainPack): string[] {
  if (!pack.lawyerReview) return [];
  return [
    `4. 本领域另有一节「${pack.lawyerReview.title}」：那几条**不得**当成把用户支给律师的理由。`,
    '   它限制的是**结论**（拿到书面确认之前不许答"是"或"否"），不是把事情交出去的许可：',
    '   争议在哪、两种说法各自的依据是什么、要确认的到底是哪一句，仍然照第 1 条由你写清楚。',
    '   说明「这一句要有执业律师的书面签字才能落成结论」不算违反第 3 条；',
    '   把整件事丢回去让用户自己找人问，仍然违反第 1 条。',
  ];
}
