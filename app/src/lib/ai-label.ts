// app/src/lib/ai-label.ts
// 《人工智能生成合成内容标识办法》（国信办通字〔2025〕2号，2025-09-01 施行）落地的**唯一措辞源**。
//
// ───────────────── ⚠️ 本文件是共用层 ⚠️ ─────────────────
// 不得出现任何具体领域的字面量。这里只有**法条要求的那几个字**；
// 「不构成哪一种专业意见」是行当话，在 DomainPack.copy.pages.aiLabelDisclaimer。
// ─────────────────────────────────────────────────────
//
// 【为什么把这几个字收成一处】办法第四条要求的是**每一个出口**都带标识：交互界面、
// 文书页、分享页、导出的文件。四处各写一遍的形态是——写四次忘一次，
// 而忘掉的那一处照常渲染、HTTP 200、页面上什么都不缺，只有法条上缺一块。
// 收口在这里之后，「有没有标识」由判据按这个常量逐处比对（ai-label.test.ts 系列）。
//
// 【显式与隐式是两件事，别混】
//   · 显式标识（§4）：人看得见的那句话 —— AI_GENERATED_LABEL。
//   · 隐式标识（§5）：写进**文件元数据**、人一般看不见的那几项 —— aiLabelPdfMeta()。
//   两者缺一不可：只加显式的形态是，文件被转存一次、那句话被删掉，就再也查不出它是谁生成的。

/**
 * 显式标识的正文（办法 §4 第（一）项：「在文本的起始、末尾或者中间适当位置添加文字提示…
 * 或者在交互场景界面、文字周边添加显著的提示标识」）。
 *
 * **领域中立**：它只说「这是 AI 生成的」，不说「所以它不是什么」。
 * 后半句按行当走 DomainPack.copy.pages.aiLabelDisclaimer，两截拼起来才是完整那句话。
 *
 * 【为什么这一截不进低调模式的糊层】低调模式把正文糊起来是为了旁人瞥不见案情；
 * 而这一句里没有任何案情，糊掉它反而与 §4「可以被用户明显感知到」直接冲突。
 * 所以渲染时 data-veil 只挂在后半截上（那半句带着行当），前半截恒清晰。
 */
export const AI_GENERATED_LABEL = '以下内容由人工智能生成合成';

/**
 * 服务提供者名称（办法 §5 要求写进文件元数据的「服务提供者名称或者编码」）。
 * 运营主体全称 + 对外品牌：验的人拿到 PDF 只看得见元数据，只写品牌名答不出「谁」。
 * 主体名与存证签章证书的 CN 同一个（docs/tasks/BOARD.md 2026-09-04 主理人确认）。
 */
export const AI_LABEL_PROVIDER = '北京天开艾洛迪心理咨询有限公司（土八鼠）';

/** 生成合成内容属性信息（办法 §5 的第一项要素）。逐字固定，不随文件类型变。 */
export const AI_LABEL_ATTRIBUTE = 'AI生成合成内容';

/**
 * 元数据里指明依据的那一行。条号取自官方原件
 * （https://www.cac.gov.cn/2025-03/14/c_1743654684782215.htm，国信办通字〔2025〕2号）——
 * 改条号要先回去核原件，不许照记忆改：写错条号的隐式标识比没有更难被发现。
 */
export const AI_LABEL_BASIS = '《人工智能生成合成内容标识办法》第五条';

/**
 * 一份导出文件的隐式标识（办法 §5）。返回的键就是 PDF 文档信息字典的字段名，
 * 由 sidecar 原样写进 reportlab 的 SimpleDocTemplate。
 *
 * @param contentNo 内容编号 —— 这一份文件在我们库里的唯一号（草稿是 `draft:<id>@v<版本>`）。
 *   **不许留空**：§5 三要素缺一项就不成其为隐式标识，而一份缺了编号的 PDF
 *   看上去与合规的那一份一模一样。空值在这里抛，不到 sidecar 才发现。
 */
export function aiLabelPdfMeta(contentNo: string): {
  producer: string;
  subject: string;
  keywords: string;
} {
  const no = contentNo.trim();
  if (!no) throw new Error('隐式标识缺少内容编号（标识办法 §5）');
  return {
    // 服务提供者名称
    producer: AI_LABEL_PROVIDER,
    // 生成合成内容属性信息 + 依据
    subject: `${AI_LABEL_ATTRIBUTE}｜${AI_LABEL_BASIS}`,
    // 内容编号（连同前两项一起重复一遍：Keywords 是最不容易被转存工具丢掉的一栏）
    keywords: `${AI_LABEL_ATTRIBUTE};服务提供者=${AI_LABEL_PROVIDER};内容编号=${no}`,
  };
}
