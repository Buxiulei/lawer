#!/bin/sh
# 跑批监视器。用法: sh watch-batch.sh <批次目录名>
#
# 【为什么不叫 batch-watch.sh】它一度叫那个名字，**结果 `ls -dt batch-*` 把监视器自己
# 当成了一个批次目录**（我的进度检查当场报错）。**工具与它的产物共用命名前缀，
# 就会被产物的通配符捞进去**——与"工具被放进产物目录"是同一个错的命名版。
#
# ─────────────────────────────────────────────────────────────
# 【已知盲区·先读这段再信它的沉默】（评测官 2026-08-25）
#
# **沉默有三种，这个脚本只能区分前两种**：
#   ① 一切正常（真沉默）
#   ② 监视器自己死了（假沉默）——外面看和①一模一样
#   ③ **出事了但不在它的职责内（盲区沉默）**——它活着、在岗、也确实没报，
#      **但它压根不管这种情况**
#
# **③ 最危险**：①② 至少还有"进程在不在"可查，**③ 连查的方向都没有**。
# 所以下面把本脚本的 ③ 逐条写出来——**将来读到它的人不会读到当时那条消息**：
#
#   ⚠️ 盲区 A：**单跑卡死但进程还活着** → 本脚本不响。
#      它只在"无 eval-agent 进程 且 无完成标记"连续 4 次时才报中断。
#      **一跑挂在那里几小时，进程数不为 0，它会一直安静。**
#      → 使用者必须自己盯挂钟：某一跑显著超过同剧本历史耗时就人工查，别等它。
#   ⚠️ 盲区 B：**跑完了但结果是错的** → 不管。它只看"跑没跑完"，不看判定内容。
#   ⚠️ 盲区 C：**别人的批次** → `pgrep` 按路径匹配 `caiyuan-ws/eval/.*eval-agent`，
#      同机另一棵树的跑批不计入，这是故意的（教训 13：进程名不是身份，路径才是）。
#
# 【为什么用 find 不用 glob】zsh 对**未匹配的 glob 直接报错终止脚本**（bash 是原样传递）。
# 上一版写 `for f in $R/batch-*/FAILED`，在**没有任何 FAILED 时**把监视器自己打死，
# 退出码 1，看起来像"批次失败"——**监视器死于它本该报告的好消息。**
# ─────────────────────────────────────────────────────────────
set -u
R=$HOME/caiyuan-ws/eval/scripts/eval/results/评测官
B=$R/$1
idle=0
while true; do
  chain=$(find "$R" -maxdepth 1 -name 'CHAIN-*' 2>/dev/null | head -1)
  [ -n "$chain" ] && { echo "✅ 批次链完成: $(head -1 "$chain")"; exit 0; }
  fail=$(find "$R" -maxdepth 2 -name FAILED -newer "$B/META" 2>/dev/null | head -1)
  [ -n "$fail" ] && { echo "❌ 批次失败 $fail : $(head -c 200 "$fail")"; exit 1; }
  n=$(pgrep -fc "caiyuan-ws/eval/.*eval-agent" 2>/dev/null || true); [ -z "$n" ] && n=0
  if [ "$n" -eq 0 ]; then idle=$((idle+1)); else idle=0; fi
  [ "$idle" -ge 4 ] && { echo "⚠️ 连续 4 次无进程且无完成标记——疑似中断（注意：卡死不在此列，见盲区 A）"; exit 2; }
  sleep 30
done
